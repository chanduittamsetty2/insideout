type Shot = [SectionKey, string, number, string?];

function shots(id: string, now: number, list: Shot[]): Media[] {
  return list.map(([section, src, age, caption], i) => ({
    id: `${id}-m${i}`,
    section,
    kind: "photo",
    src,
    capturedAt: now - age,
    caption,
  }));
}

